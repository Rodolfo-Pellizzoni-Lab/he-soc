/*
 * PMU Firmware - Single-Function Entry/Exit Profiler
 *
 * Tracks one function (func_l1_cold) using a single PC milestone slot:
 *   State WAIT_ENTRY: slot 0 = FUNC_ENTRY
 *     -> hit: reset counters, snapshot mcycle, reprogram to FUNC_EXIT
 *   State WAIT_EXIT:  slot 0 = FUNC_EXIT
 *     -> hit: snapshot all counters, log result, reprogram to FUNC_ENTRY
 *
 * Expected per call (N_ITER=64, CL_WORDS=16):
 *   loads = N_ITER = 64, L1D_misses = N_ITER = 64
 *
 * DSPM log layout (at DSPM_BASE_ADDR + 0x2000):
 *   +0x00: call_count    (completed entry->exit pairs)
 *   +0x04: state         (0=wait_entry, 1=wait_exit)
 *   +0x08: result        (9 metrics x 4B = 36B for last completed call)
 *          [cycles, L1miss, stalls, LLC_RD, LLC_WR, MEM_RD, MEM_WR, rdlat, wrlat]
 *
 *   cnt.wr: .word 0x00e79007  (a5=counter_idx, a4=value)
 */

#include <stddef.h>
#include <stdint.h>
#include "include/pmu_hw_desc.h"

// DSPM communication addresses (must match CVA6 pmu_simple_bench.c)
#define DSPM_STATUS_ADDR        (DSPM_BASE_ADDR + 0x00)
#define DSPM_CMD_ADDR           (DSPM_BASE_ADDR + 0x80)

// DSPM log layout
#define DSPM_LOG_BASE           (DSPM_BASE_ADDR + 0x2000)
#define DSPM_LOG_CALL_COUNT     (DSPM_LOG_BASE + 0x00)
#define DSPM_LOG_STATE          (DSPM_LOG_BASE + 0x04)
#define DSPM_LOG_RESULT         (DSPM_LOG_BASE + 0x08)   // 9 metrics x 4B
#define DSPM_LOG_PMU_INSTRET    (DSPM_LOG_BASE + 0x30)  // total Ibex instret
#define DSPM_LOG_INSTRET_ENTRY  (DSPM_LOG_BASE + 0x34)  // instret at entry wake
#define DSPM_LOG_INSTRET_EXIT   (DSPM_LOG_BASE + 0x38)  // instret at exit wake
#define DSPM_LOG_MCYCLE_ENTRY   (DSPM_LOG_BASE + 0x3C)  // mcycle at entry wake
#define DSPM_LOG_MCYCLE_EXIT    (DSPM_LOG_BASE + 0x40)  // mcycle at exit wake

// Status codes
#define STATUS_STARTED          0xBB000001
#define STATUS_SENDING_IRQS     0xBB000010
#define STATUS_ALL_IRQS_SENT    0xBB000099

// Command codes
#define CMD_NONE                0x00000000
#define CMD_TRIGGER_INTERRUPT   0x000000FF

// Memory access macros
#define WRITE_MEM(addr, value)  (*((volatile uint32_t*)(addr)) = (value))
#define READ_MEM(addr)          (*((volatile uint32_t*)(addr)))

// Counter indices
#define CNT_IRQ_BASE       0
#define CNT_LLC_RD_C0      4    // LLC read requests core 0
#define CNT_LLC_WR_C0      8    // LLC write requests core 0
#define CNT_MEM_RD_C0      12   // MEM read requests core 0
#define CNT_MEM_WR_C0      16   // MEM write requests core 0
#define CNT_MILESTONE_0    20   // PC milestone slot 0 hit count
#define CNT_L1_MISS        22   // L1-D misses (EVU EV0)
#define CNT_STALLS         23   // pipeline stalls (EVU EV2)
#define CNT_TOTAL_CYCLES   25   // firmware writes total mcycle here
#define CNT_BREADCRUMB     26   // debug breadcrumb
#define CNT_MEM_RD_LAT     27   // MEM read response latency (core 0)
#define CNT_MEM_WR_LAT     28   // MEM write response latency (core 0)

// Milestone hardware register (slot 0)
#define PC_MILESTONE_SLOT0      0x10606010

// Addresses injected at build time via -DFUNC_ENTRY=... -DFUNC_EXIT=...
// (generated by extract_simple_addrs.py from the CVA6 binary dump).
// The values below are stale placeholders; the two-pass build overrides them.
#ifndef FUNC_ENTRY
#define FUNC_ENTRY  0x80002d02   // PLACEHOLDER — override via build system
#endif
#ifndef FUNC_EXIT
#define FUNC_EXIT   0x80002d18   // PLACEHOLDER — override via build system
#endif

/*
 * Write value to counter using custom instruction
 */
static inline void cnt_wr(uint32_t counter_idx, uint32_t value) {
    asm volatile(
        "mv a5, %0\n\t"
        "mv a4, %1\n\t"
        ".word 0x00e79007\n\t"
        :
        : "r" (counter_idx), "r" (value)
        : "a4", "a5"
    );
}

/*
 * Read value from counter using custom instruction
 */
static inline uint32_t cnt_rd(uint32_t counter_idx) {
    uint32_t value;
    asm volatile(
        "mv a5, %1\n\t"
        ".word 0x00078707\n\t"
        "mv %0, a4\n\t"
        : "=r" (value)
        : "r" (counter_idx)
        : "a4", "a5"
    );
    return value;
}

/*
 * Wait-for-Pending: sleep until any counter in bitmap has its pending bit set.
 * Returns bitmap of which counter(s) woke us.
 * Encoding: 0x00072887 (rd=x17=woke_bitmap, rs1=x14=monitor_bitmap)
 */
static inline uint32_t cnt_wfp(uint32_t counter_bitmap) {
    uint32_t woke_bitmap;
    asm volatile(
        "mv x14, %1\n\t"
        ".word 0x00072887\n\t"
        "mv %0, x17\n\t"
        : "=r" (woke_bitmap)
        : "r" (counter_bitmap)
        : "x14", "x17"
    );
    return woke_bitmap;
}

int main() {
    asm volatile ("nop");
    asm volatile ("nop");
    asm volatile ("nop");
    asm volatile ("nop");

    WRITE_MEM(0x10429000, 0xC4A0E440);

    // Enable mcycle counter
    asm volatile ("csrw 0x320, zero");

    // Clear command
    WRITE_MEM(DSPM_CMD_ADDR, CMD_NONE);

    // Clear overflow hardware for IRQ counters at boot
    for (uint32_t c = 0; c < 4; c++)
        cnt_wr(CNT_IRQ_BASE + c, 0x00000000);

    // Clear DSPM log area
    for (uint32_t i = 0; i < 0x80; i += 4)
        WRITE_MEM(DSPM_LOG_BASE + i, 0);

    // Signal PMU started
    WRITE_MEM(DSPM_STATUS_ADDR, STATUS_STARTED);

    // Wait for command from CVA6
    while (READ_MEM(DSPM_CMD_ADDR) != CMD_TRIGGER_INTERRUPT)
        asm volatile ("nop");

    // Clear command
    WRITE_MEM(DSPM_CMD_ADDR, CMD_NONE);

    // Status handshake
    WRITE_MEM(DSPM_STATUS_ADDR, STATUS_SENDING_IRQS);
    WRITE_MEM(DSPM_STATUS_ADDR, STATUS_ALL_IRQS_SENT);

    cnt_wr(CNT_BREADCRUMB, 1);

    // Write EVU event ID config FIRST (writing 0x10606000 can reset milestone state)
    WRITE_MEM(0x10606000, 0x00000002);

    // Program slot 0 with entry address
    WRITE_MEM(PC_MILESTONE_SLOT0, FUNC_ENTRY);

    // Clear all stat counters
    cnt_wr(CNT_LLC_RD_C0, 0);
    cnt_wr(CNT_LLC_WR_C0, 0);
    cnt_wr(CNT_MEM_RD_C0, 0);
    cnt_wr(CNT_MEM_WR_C0, 0);
    cnt_wr(CNT_L1_MISS, 0);
    cnt_wr(CNT_STALLS, 0);

    cnt_wr(CNT_MILESTONE_0, 0);

    uint32_t mcycle_entry = 0;
    uint32_t call_count = 0;
    uint32_t milestone_mask = (1 << CNT_MILESTONE_0);  // bit 20

    uint32_t cyc_start;
    asm volatile ("csrr %0, mcycle" : "=r"(cyc_start));

    // Snapshot minstret before entering the sleep loop
    uint32_t instret_start;
    asm volatile ("csrr %0, minstret" : "=r"(instret_start));

    WRITE_MEM(DSPM_LOG_STATE, 0);
    cnt_wr(CNT_BREADCRUMB, 2);

    while (1) {
        // ---- SLEEP until entry milestone fires ----
        cnt_wfp(milestone_mask);

        // ---- ENTRY HIT: snapshot all counters back-to-back ----
        uint32_t e_cyc, e_l1, e_stall, e_llcrd, e_llcwr, e_memrd, e_memwr, e_rlat, e_wlat;
        uint32_t e_instret;
        asm volatile ("csrr %0, mcycle"   : "=r"(e_cyc));
        asm volatile ("csrr %0, minstret" : "=r"(e_instret));
        e_l1    = cnt_rd(CNT_L1_MISS)    & 0x7FFFFFFF;
        e_stall = cnt_rd(CNT_STALLS)     & 0x7FFFFFFF;
        e_llcrd = cnt_rd(CNT_LLC_RD_C0)  & 0x7FFFFFFF;
        e_llcwr = cnt_rd(CNT_LLC_WR_C0)  & 0x7FFFFFFF;
        e_memrd = cnt_rd(CNT_MEM_RD_C0)  & 0x7FFFFFFF;
        e_memwr = cnt_rd(CNT_MEM_WR_C0)  & 0x7FFFFFFF;
        e_rlat  = cnt_rd(CNT_MEM_RD_LAT) & 0x7FFFFFFF;
        e_wlat  = cnt_rd(CNT_MEM_WR_LAT) & 0x7FFFFFFF;

        // Reprogram to exit
        WRITE_MEM(PC_MILESTONE_SLOT0, FUNC_EXIT);

        // ---- SLEEP until exit milestone fires ----
        cnt_wfp(milestone_mask);

        // ---- EXIT HIT: snapshot all counters back-to-back ----
        uint32_t x_cyc, x_l1, x_stall, x_llcrd, x_llcwr, x_memrd, x_memwr, x_rlat, x_wlat;
        uint32_t x_instret;
        asm volatile ("csrr %0, mcycle"   : "=r"(x_cyc));
        asm volatile ("csrr %0, minstret" : "=r"(x_instret));
        x_l1    = cnt_rd(CNT_L1_MISS)    & 0x7FFFFFFF;
        x_stall = cnt_rd(CNT_STALLS)     & 0x7FFFFFFF;
        x_llcrd = cnt_rd(CNT_LLC_RD_C0)  & 0x7FFFFFFF;
        x_llcwr = cnt_rd(CNT_LLC_WR_C0)  & 0x7FFFFFFF;
        x_memrd = cnt_rd(CNT_MEM_RD_C0)  & 0x7FFFFFFF;
        x_memwr = cnt_rd(CNT_MEM_WR_C0)  & 0x7FFFFFFF;
        x_rlat  = cnt_rd(CNT_MEM_RD_LAT) & 0x7FFFFFFF;
        x_wlat  = cnt_rd(CNT_MEM_WR_LAT) & 0x7FFFFFFF;

        // Write deltas to DSPM
        WRITE_MEM(DSPM_LOG_RESULT + 0,  x_cyc   - e_cyc);
        WRITE_MEM(DSPM_LOG_RESULT + 4,  x_l1    - e_l1);
        WRITE_MEM(DSPM_LOG_RESULT + 8,  x_stall - e_stall);
        WRITE_MEM(DSPM_LOG_RESULT + 12, x_llcrd - e_llcrd);
        WRITE_MEM(DSPM_LOG_RESULT + 16, x_llcwr - e_llcwr);
        WRITE_MEM(DSPM_LOG_RESULT + 20, x_memrd - e_memrd);
        WRITE_MEM(DSPM_LOG_RESULT + 24, x_memwr - e_memwr);
        WRITE_MEM(DSPM_LOG_RESULT + 28, x_rlat  - e_rlat);
        WRITE_MEM(DSPM_LOG_RESULT + 32, x_wlat  - e_wlat);

        // Instret/mcycle tracking
        WRITE_MEM(DSPM_LOG_INSTRET_ENTRY, e_instret);
        WRITE_MEM(DSPM_LOG_INSTRET_EXIT, x_instret);
        WRITE_MEM(DSPM_LOG_MCYCLE_ENTRY, e_cyc);
        WRITE_MEM(DSPM_LOG_MCYCLE_EXIT, x_cyc);
        WRITE_MEM(DSPM_LOG_PMU_INSTRET, x_instret - instret_start);

        call_count++;
        WRITE_MEM(DSPM_LOG_CALL_COUNT, call_count);

        // Reprogram slot 0 back to entry
        WRITE_MEM(PC_MILESTONE_SLOT0, FUNC_ENTRY);

        cnt_wr(CNT_BREADCRUMB, 20 + call_count);

        uint32_t cyc_now;
        asm volatile ("csrr %0, mcycle" : "=r"(cyc_now));
        cnt_wr(CNT_TOTAL_CYCLES, cyc_now - cyc_start);

    }
}
